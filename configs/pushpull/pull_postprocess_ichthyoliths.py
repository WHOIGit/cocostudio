"""Project-specific COCO postprocessing for ichthyolith pull exports."""

from __future__ import annotations

import re
from typing import Any


def compute_coco_localization_meta(coco: dict) -> None:
    """Derive local ROI/object metadata from cocostudio-pushed LS region IDs.

    This understands region IDs generated by:

        region_id_pattern = "roi_{annotation.meta.roi_id}"

    It mutates ``coco`` in place.
    """
    for annotation in coco.get("annotations", []):
        meta = annotation.setdefault("meta", {})
        if not isinstance(meta, dict):
            continue

        roi_id = _roi_id_from_region_id(meta.get("ls_region_id"))
        if roi_id is not None:
            meta.setdefault("roi_id", roi_id)

        obj_id = _obj_id_from_roi_id(meta.get("roi_id"))
        if obj_id is not None:
            meta.setdefault("obj_id", obj_id)


def _roi_id_from_region_id(region_id: Any) -> str | None:
    if not isinstance(region_id, str):
        return None
    if region_id.startswith("roi_") and len(region_id) > 4:
        return region_id[4:]
    return None


def _obj_id_from_roi_id(roi_id: Any) -> int | None:
    if not isinstance(roi_id, str):
        return None
    match = re.search(r"(?:^|_)obj0*([0-9]+)(?:_|$)", roi_id)
    if not match:
        return None
    return int(match.group(1))
